def reward_function(params):
    if (not params['all_wheels_on_track'] or params.get('is_offtrack', False)
            or params.get('is_crashed', False)):
        return 0.001

    x, y = params['x'], params['y']
    best_squared = float('inf')
    tangent = 0.0
    for i, (ax, ay) in enumerate(RACING_LINE):
        bx, by = RACING_LINE[(i + 1) % len(RACING_LINE)]
        dx, dy = bx - ax, by - ay
        squared_length = dx * dx + dy * dy
        fraction = max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / squared_length))
        squared_distance = (x - ax - fraction * dx)**2 + (y - ay - fraction * dy)**2
        if squared_distance < best_squared:
            best_squared = squared_distance
            tangent = math.atan2(dy, dx)

    # Broad, smooth distance reward: the learner need not hit a narrow line.
    tolerance = max(0.10, 0.35 * params['track_width'])
    line_score = math.exp(-best_squared / tolerance**2)
    heading_error = math.radians(params['heading']) - tangent
    direction_score = max(0.0, math.cos(heading_error))**2
    # A small speed preference, gated by direction and line quality.
    # First-trial action space: 0.8 to 2.0 m/s. This is not a corner speed cap.
    speed_score = min(1.0, max(0.0, params['speed']) / 2.0)
    return float(0.001 + direction_score * (0.2 + 0.8 * line_score)
                 * (0.7 + 0.3 * speed_score))
